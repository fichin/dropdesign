import type pg from 'pg'
import type { Comment } from '../../../shared/kanban.ts'
import { initialsAvatar, nameFromEmail } from '../../../shared/people.ts'
import { withTransaction } from '../db/pool.ts'
import { conflict, forbidden, HttpError, notFound } from '../errors.ts'

type Db = pg.Pool | pg.PoolClient

interface CommentRow {
  id: string
  task_id: string
  body: string
  created_at: Date
  author_id: string
  author_name: string
  author_avatar_url: string
  author_user_id: string | null
}

const COMMENT_SELECT = `
  SELECT c.id, c.task_id, c.body, c.created_at,
         p.id AS author_id, p.name AS author_name, p.avatar_url AS author_avatar_url, p.user_id AS author_user_id
  FROM comments c
  JOIN people p ON p.id = c.author_id`

const toComment = (row: CommentRow): Comment => ({
  id: row.id,
  taskId: row.task_id,
  body: row.body,
  createdAt: row.created_at.toISOString(),
  author: { id: row.author_id, name: row.author_name, avatarUrl: row.author_avatar_url },
  authorUserId: row.author_user_id,
})

/** The person a signed-in account comments as, created the first time it's needed */
async function personForUser(client: pg.PoolClient, userId: string): Promise<string> {
  const { rows: [existing] } = await client.query<{ id: string }>('SELECT id FROM people WHERE user_id = $1', [userId])
  if (existing) return existing.id

  const { rows: [user] } = await client.query<{ email: string }>('SELECT email FROM users WHERE id = $1', [userId])
  // A valid session for an account that has since been deleted
  if (!user) throw new HttpError(401, 'Not signed in')
  const name = nameFromEmail(user.email)
  // ON CONFLICT: two first comments at once from the same account still make one person
  const { rows: [person] } = await client.query<{ id: string }>(
    `INSERT INTO people (name, avatar_url, user_id) VALUES ($1, $2, $3)
     ON CONFLICT (user_id) DO UPDATE SET user_id = EXCLUDED.user_id
     RETURNING id`,
    [name, initialsAvatar(name), userId],
  )
  return person.id
}

async function assertTaskExists(db: Db, taskId: string, { lock = false } = {}) {
  const { rowCount } = await db.query(`SELECT 1 FROM tasks WHERE id = $1${lock ? ' FOR UPDATE' : ''}`, [taskId])
  if (!rowCount) throw notFound('Task not found')
}

/** A task's comments, oldest first */
export async function listComments(db: Db, taskId: string): Promise<Comment[]> {
  await assertTaskExists(db, taskId)
  const { rows } = await db.query<CommentRow>(`${COMMENT_SELECT} WHERE c.task_id = $1 ORDER BY c.created_at, c.id`, [
    taskId,
  ])
  return rows.map(toComment)
}

export interface AddCommentInput {
  /** Generated by the client, so a retried request can't post the comment twice */
  id: string
  body: string
}

/**
 * Adds a comment as the signed-in user and keeps tasks.comment_count in step.
 * Returns the comment and the task's new comment count.
 */
export async function addComment(pool: pg.Pool, taskId: string, userId: string, input: AddCommentInput) {
  return withTransaction(pool, async (client) => {
    // Locks the task row: a concurrent delete of the task waits, and the count stays exact
    await assertTaskExists(client, taskId, { lock: true })
    const authorId = await personForUser(client, userId)

    const { rows: [existing] } = await client.query<CommentRow>(`${COMMENT_SELECT} WHERE c.id = $1`, [input.id])
    if (existing) {
      // The same request arriving twice is fine; anything else reusing the id isn't
      if (existing.task_id === taskId && existing.author_id === authorId && existing.body === input.body) {
        const { rows: [task] } = await client.query<{ comment_count: number }>(
          'SELECT comment_count FROM tasks WHERE id = $1',
          [taskId],
        )
        return { comment: toComment(existing), commentCount: task.comment_count, created: false }
      }
      throw conflict('A different comment already uses this id')
    }

    await client.query('INSERT INTO comments (id, task_id, author_id, body) VALUES ($1, $2, $3, $4)', [
      input.id,
      taskId,
      authorId,
      input.body,
    ])
    const { rows: [task] } = await client.query<{ comment_count: number }>(
      'UPDATE tasks SET comment_count = comment_count + 1 WHERE id = $1 RETURNING comment_count',
      [taskId],
    )
    const { rows: [row] } = await client.query<CommentRow>(`${COMMENT_SELECT} WHERE c.id = $1`, [input.id])
    return { comment: toComment(row), commentCount: task.comment_count, created: true }
  })
}

/** Deletes a comment, but only the author's own. Returns the task and its new comment count */
export async function deleteComment(pool: pg.Pool, commentId: string, userId: string) {
  return withTransaction(pool, async (client) => {
    const { rows: [comment] } = await client.query<{ task_id: string; author_user_id: string | null }>(
      `SELECT c.task_id, p.user_id AS author_user_id
       FROM comments c JOIN people p ON p.id = c.author_id
       WHERE c.id = $1
       FOR UPDATE OF c`,
      [commentId],
    )
    if (!comment) throw notFound('Comment not found')
    if (comment.author_user_id !== userId) throw forbidden('You can only delete your own comments')

    await client.query('DELETE FROM comments WHERE id = $1', [commentId])
    const { rows: [task] } = await client.query<{ comment_count: number }>(
      'UPDATE tasks SET comment_count = GREATEST(comment_count - 1, 0) WHERE id = $1 RETURNING comment_count',
      [comment.task_id],
    )
    return { taskId: comment.task_id, commentCount: task.comment_count }
  })
}
