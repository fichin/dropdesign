import type pg from 'pg'
import type { Assignee, Board, Column, Priority, Task, TaskStatus } from '../../../shared/kanban.ts'
import { withTransaction } from '../db/pool.ts'
import { conflict, notFound } from '../errors.ts'

type Db = pg.Pool | pg.PoolClient

interface TaskRow {
  id: string
  column_id: string
  title: string
  priority: Priority
  progress: number
  comment_count: number
  completed_subtask_count: number
  assignees: Assignee[]
}

// Tasks with their assignees (in display order) as a JSON array
const TASK_SELECT = `
  SELECT t.id, t.column_id, t.title, t.priority, t.progress, t.comment_count, t.completed_subtask_count,
         COALESCE(
           json_agg(json_build_object('id', p.id, 'name', p.name, 'avatarUrl', p.avatar_url) ORDER BY ta.position)
             FILTER (WHERE p.id IS NOT NULL),
           '[]'
         ) AS assignees
  FROM tasks t
  JOIN columns c ON c.id = t.column_id
  LEFT JOIN task_assignees ta ON ta.task_id = t.id
  LEFT JOIN people p ON p.id = ta.person_id`

const toTask = (row: TaskRow): Task => ({
  id: row.id,
  title: row.title,
  priority: row.priority,
  progress: row.progress,
  assignees: row.assignees,
  commentCount: row.comment_count,
  completedSubtaskCount: row.completed_subtask_count,
})

export async function listBoards(db: Db) {
  const { rows } = await db.query<{ id: string; title: string }>(
    'SELECT id, title FROM boards ORDER BY created_at, id',
  )
  return rows
}

/** The whole board in the shape the frontend uses (shared/kanban.ts) */
export async function getBoard(db: Db, boardId: string): Promise<Board> {
  const { rows: [board] } = await db.query<{ id: string; title: string }>(
    'SELECT id, title FROM boards WHERE id = $1',
    [boardId],
  )
  if (!board) throw notFound('Board not found')

  const { rows: columnRows } = await db.query<{ id: string; title: string; status: TaskStatus }>(
    'SELECT id, title, status FROM columns WHERE board_id = $1 ORDER BY position',
    [boardId],
  )
  const { rows: taskRows } = await db.query<TaskRow>(
    `${TASK_SELECT} WHERE c.board_id = $1 GROUP BY t.id ORDER BY t.position`,
    [boardId],
  )

  const columns: Record<string, Column> = {}
  for (const column of columnRows) columns[column.id] = { ...column, taskIds: [] }
  const tasks: Record<string, Task> = {}
  for (const row of taskRows) {
    tasks[row.id] = toTask(row)
    columns[row.column_id].taskIds.push(row.id)
  }

  return { id: board.id, title: board.title, tasks, columns, columnOrder: columnRows.map((c) => c.id) }
}

async function getTask(db: Db, taskId: string): Promise<Task> {
  const { rows: [row] } = await db.query<TaskRow>(`${TASK_SELECT} WHERE t.id = $1 GROUP BY t.id`, [taskId])
  if (!row) throw notFound('Task not found')
  return toTask(row)
}

/**
 * Every change to a board first locks the board's row, so changes to the same
 * board take turns. Locking individual task/column rows instead could deadlock
 * (a move and an add each holding a row the other needs).
 */
async function lockBoard(client: pg.PoolClient, boardId: string) {
  const { rowCount } = await client.query('SELECT 1 FROM boards WHERE id = $1 FOR UPDATE', [boardId])
  if (!rowCount) throw notFound('Board not found')
}

/** Rewrites positions 0..n-1 (and the column) for these task ids, in this order */
async function placeTasks(client: pg.PoolClient, columnId: string, taskIds: string[]) {
  if (taskIds.length === 0) return
  await client.query(
    `UPDATE tasks AS t
     SET column_id = $1, position = o.ordinality - 1
     FROM unnest($2::uuid[]) WITH ORDINALITY AS o(id, ordinality)
     WHERE t.id = o.id AND (t.column_id <> $1 OR t.position <> o.ordinality - 1)`,
    [columnId, taskIds],
  )
}

async function columnTaskIds(client: pg.PoolClient, columnId: string): Promise<string[]> {
  const { rows } = await client.query<{ id: string }>(
    'SELECT id FROM tasks WHERE column_id = $1 ORDER BY position',
    [columnId],
  )
  return rows.map((row) => row.id)
}

export interface AddTaskInput {
  /** Generated by the client, so a retried request can't create a duplicate */
  id: string
  columnId: string
  title: string
}

/** Adds a task at the top of the column; in a Completed column it starts at 100% */
export async function addTask(pool: pg.Pool, boardId: string, input: AddTaskInput) {
  return withTransaction(pool, async (client) => {
    await lockBoard(client, boardId)

    const { rows: [column] } = await client.query<{ status: TaskStatus }>(
      'SELECT status FROM columns WHERE id = $1 AND board_id = $2',
      [input.columnId, boardId],
    )
    if (!column) throw notFound('Column not found on this board')

    const { rows: [existing] } = await client.query<{ column_id: string; title: string }>(
      'SELECT column_id, title FROM tasks WHERE id = $1',
      [input.id],
    )
    if (existing) {
      // The same request arriving twice (e.g. a retry) is fine; a different task reusing the id isn't
      if (existing.column_id === input.columnId && existing.title === input.title) {
        return { task: await getTask(client, input.id), created: false }
      }
      throw conflict('A different task already uses this id')
    }

    await client.query('UPDATE tasks SET position = position + 1 WHERE column_id = $1', [input.columnId])
    await client.query(
      'INSERT INTO tasks (id, column_id, title, progress, position) VALUES ($1, $2, $3, $4, 0)',
      [input.id, input.columnId, input.title, column.status === 'completed' ? 100 : 0],
    )
    return { task: await getTask(client, input.id), created: true }
  })
}

export interface MoveTaskInput {
  toColumnId: string
  /** Position in the destination column once the move is done; clamped to the column's length */
  toIndex: number
}

/**
 * Places a task in a column at a position (reordering, or moving between columns).
 * Arriving in a Completed column sets progress to 100. Returns the task and the
 * new order of every column that changed.
 */
export async function moveTask(pool: pg.Pool, taskId: string, input: MoveTaskInput) {
  return withTransaction(pool, async (client) => {
    const { rows: [located] } = await client.query<{ board_id: string }>(
      'SELECT c.board_id FROM tasks t JOIN columns c ON c.id = t.column_id WHERE t.id = $1',
      [taskId],
    )
    if (!located) throw notFound('Task not found')
    await lockBoard(client, located.board_id)

    // Re-read now that the board is locked: nothing else can move the task any more
    const { rows: [task] } = await client.query<{ column_id: string; progress: number }>(
      'SELECT column_id, progress FROM tasks WHERE id = $1',
      [taskId],
    )
    if (!task) throw notFound('Task not found')
    const { rows: [toColumn] } = await client.query<{ status: TaskStatus }>(
      'SELECT status FROM columns WHERE id = $1 AND board_id = $2',
      [input.toColumnId, located.board_id],
    )
    if (!toColumn) throw notFound('Column not found on this board')

    const fromColumnId = task.column_id
    const isSameColumn = fromColumnId === input.toColumnId
    const fromIds = await columnTaskIds(client, fromColumnId)
    const remaining = (isSameColumn ? fromIds : await columnTaskIds(client, input.toColumnId)).filter(
      (id) => id !== taskId,
    )
    const toIndex = Math.min(input.toIndex, remaining.length)
    const toIds = [...remaining.slice(0, toIndex), taskId, ...remaining.slice(toIndex)]

    const changed: Record<string, string[]> = {}
    if (!(isSameColumn && fromIds.indexOf(taskId) === toIndex)) {
      await placeTasks(client, input.toColumnId, toIds)
      changed[input.toColumnId] = toIds
      if (!isSameColumn) {
        const fromRemaining = fromIds.filter((id) => id !== taskId)
        await placeTasks(client, fromColumnId, fromRemaining)
        changed[fromColumnId] = fromRemaining
      }
      const completes = !isSameColumn && toColumn.status === 'completed' && task.progress !== 100
      await client.query(
        `UPDATE tasks SET updated_at = now()${completes ? ', progress = 100' : ''} WHERE id = $1`,
        [taskId],
      )
    }

    return { task: await getTask(client, taskId), columns: changed }
  })
}
